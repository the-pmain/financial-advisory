export function applyDocumentMock(kind, current) {
  const mock = DOCUMENT_MOCK[kind];
  if (!mock) return { ...current };
  const next = { ...current, ...mock };
  for (const key of LOCKED) {
    if (key === 'feeEarner') continue;
    delete next[key];
    next[key] = '';
  }
  if (current.feeEarner) next.feeEarner = current.feeEarner;
  for (const keep of ['clientName', 'applicant', 'wsName', 'sellerName']) {
    if (String(current[keep] || '').trim()) next[keep] = current[keep];
  }
  return next;
}
